#!/usr/bin/env python3
"""Turn assets/page-shell.html into a C++ byte array, page_shell.inc.

The first page must be one self-contained file, so the favicon, the wordmark
and the background image are placed inside it as data. The result is compiled
into the orchestrator as bytes. The Makefile runs this; the output is build
output and is not kept in the repository.

  embed_page.py OUTPUT_FILE
"""
import base64
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets'


def data(name, kind):
    return f'data:{kind};base64,' + base64.b64encode((ASSETS / name).read_bytes()).decode()


def generated():
    shell = (ASSETS / 'page-shell.html').read_text()
    for marker, value in (('@FAVICON@', data('fortis-favicon.svg', 'image/svg+xml')),
                          ('@LOCKUP@', data('fortisnet-lockup.svg', 'image/svg+xml')),
                          ('@HERO@', data('node-hall.webp', 'image/webp'))):
        if shell.count(marker) != 1:
            raise SystemExit(f'page-shell.html must contain {marker} exactly once')
        shell = shell.replace(marker, value)
    raw = shell.encode()
    rows = [', '.join(str(byte) for byte in raw[start:start + 24]) for start in range(0, len(raw), 24)]
    return ('// Generated by tools/embed_page.py from assets/page-shell.html and the brand\n'
            '// files beside it. Do not edit: change the assets and build again.\n'
            'inline constexpr unsigned char kPageShell[] = {\n    ' + ',\n    '.join(rows) + '};\n')


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    output = Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generated())
    return 0


if __name__ == '__main__':
    sys.exit(main())
